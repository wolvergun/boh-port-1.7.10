package net.mcreator.boh.client.renderer;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.mcreator.boh.entity.StiltwalkerEntity;
import net.mcreator.boh.entity.layer.StiltwalkerLayer;
import net.mcreator.boh.entity.model.StiltwalkerModel;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.EntityRendererProvider.Context;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.cache.object.BakedGeoModel;
import software.bernie.geckolib.renderer.GeoEntityRenderer;

public class StiltwalkerRenderer extends GeoEntityRenderer<StiltwalkerEntity> {
   public StiltwalkerRenderer(Context renderManager) {
      super(renderManager, new StiltwalkerModel());
      this.shadowRadius = 0.8F;
      this.addRenderLayer(new StiltwalkerLayer(this));
   }

   public RenderType getRenderType(StiltwalkerEntity animatable, ResourceLocation texture, MultiBufferSource bufferSource, float partialTick) {
      return RenderType.entityTranslucent(this.getTextureLocation(animatable));
   }

   public void preRender(
      PoseStack poseStack,
      StiltwalkerEntity entity,
      BakedGeoModel model,
      MultiBufferSource bufferSource,
      VertexConsumer buffer,
      boolean isReRender,
      float partialTick,
      int packedLight,
      int packedOverlay,
      float red,
      float green,
      float blue,
      float alpha
   ) {
      float scale = 1.8F;
      this.scaleHeight = scale;
      this.scaleWidth = scale;
      super.preRender(poseStack, entity, model, bufferSource, buffer, isReRender, partialTick, packedLight, packedOverlay, red, green, blue, alpha);
   }

   protected float getDeathMaxRotation(StiltwalkerEntity entityLivingBaseIn) {
      return 0.0F;
   }
}
